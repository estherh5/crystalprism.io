#!/usr/bin/env node
// Writes the repo-root `_redirects` that serves each legacy app from its own
// subdomain (one Netlify site, the hosts are domain aliases of it).
//
//   node tools/subdomains/build-redirects.mjs
//
// Rule order (Netlify uses the first match):
//   1. per host, a forced rewrite for each SHARED root file the app's pages
//      reach via ../ (common.js, common.css, ...) that the app lacks itself,
//      computed from the app's own src/href/url() references, never listed
//      by hand, so an app-owned file of the same name still wins; plus
//      EVERY_HOST (/slash.js) on every host;
//   2. per host, one EXACT-path 301 per app folder page (computed from the
//      tree): Netlify's add-a-trailing-slash 301 for `/easel` names the
//      rewritten path (`/canvashare/easel/`), which would otherwise be
//      rewritten again into `/canvashare/canvashare/easel/` and 404. Never a
//      `/<dir>/*` wildcard: slash normalization lets it drop the slash from
//      :splat and loop;
//   3. per host, everything else rewrites into the app's directory;
//   4. on the apex and www, every old /<dir>/ URL 301s to its subdomain
//      (Netlify carries the query string through a 301).
// tests/subdomain-routing.test.js checks the output with its own resolver.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

export const APP_DIRS = {
  'timespace': 'timespace', 'vicarious': 'vicarious',
  'canvashare': 'canvashare', 'thought-writer': 'thought-writer',
  'shapes-in-rain': 'shapes-in-rain', 'rhythm-of-life': 'rhythm-of-life',
  'account': 'user',
};
const APEXES = ['https://crystalprism.io', 'https://www.crystalprism.io'];
// Root files every app host serves whether or not its pages reference them
const EVERY_HOST = ['/slash.js', '/apps.json'];
const HEADER = '# Generated by tools/subdomains/build-redirects.mjs — do not edit by hand.';
const EXTERNAL = /^(https?:|data:|#|mailto:|javascript:|tel:|\/\/)/i;

function filesUnder(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? filesUnder(full) : [full];
  }).sort();
}

function refsIn(file) {
  const text = fs.readFileSync(file, 'utf8');
  const grab = (re) => [...text.matchAll(re)].map((m) => m[1]);
  const css = grab(/url\(\s*["']?([^"')]+)["']?\s*\)/gi);
  switch (path.extname(file)) {
    case '.html': return grab(/\b(?:src|href)\s*=\s*["']([^"']*)["']/gi).concat(css);
    case '.css': return css;
    case '.js': return grab(/['"](\.\.?\/[^'"\s]*)['"]/g);
    default: return [];
  }
}

const isFile = (p) => fs.existsSync(p) && fs.statSync(p).isFile();

// Root paths that `host`'s pages reach and that only the repo root can serve
function sharedFiles(host, dir) {
  const appDir = path.join(ROOT, dir);
  const shared = new Set();
  const queue = filesUnder(appDir)
    .filter((f) => ['.html', '.css', '.js'].includes(path.extname(f)))
    .map((file) => ({
      file,
      base: `https://${host}.crystalprism.io/`
        + path.relative(appDir, file).split(path.sep).join('/'),
    }));
  while (queue.length) {
    const { file, base } = queue.shift();
    for (const ref of refsIn(file)) {
      if (!ref || EXTERNAL.test(ref)) continue;
      const p = decodeURIComponent(new URL(ref, base).pathname);
      if (p.endsWith('/') || isFile(path.join(appDir, p))) continue;
      if (!isFile(path.join(ROOT, p)) || shared.has(p)) continue;
      shared.add(p);
      // A shared stylesheet's own url()s resolve on the subdomain too
      if (p.endsWith('.css')) {
        queue.push({ file: path.join(ROOT, p), base: `https://${host}.crystalprism.io${p}` });
      }
    }
  }
  for (const p of EVERY_HOST) {
    if (!isFile(path.join(appDir, p))) shared.add(p);
  }
  return [...shared].sort();
}

// App folders below the app root that hold a page, e.g. ['easel']
function folderPages(dir) {
  const appDir = path.join(ROOT, dir);
  return filesUnder(appDir)
    .map((f) => path.relative(appDir, f).split(path.sep).join('/'))
    .filter((rel) => rel.endsWith('/index.html'))
    .map((rel) => rel.slice(0, -'/index.html'.length));
}

export function buildRedirects() {
  const lines = [HEADER, ''];
  lines.push('# Shared root files each app loads via ../');
  for (const [host, dir] of Object.entries(APP_DIRS)) {
    for (const p of sharedFiles(host, dir)) {
      lines.push(`https://${host}.crystalprism.io${p}  ${p}  200!`);
    }
  }
  lines.push('', "# Netlify's folder-slash 301 names the rewritten path; send it back");
  for (const [host, dir] of Object.entries(APP_DIRS)) {
    for (const sub of folderPages(dir)) {
      const origin = `https://${host}.crystalprism.io`;
      lines.push(`${origin}/${dir}/${sub}  ${origin}/${sub}/  301!`);
    }
  }
  lines.push('', '# Each app host serves its directory');
  for (const [host, dir] of Object.entries(APP_DIRS)) {
    lines.push(`https://${host}.crystalprism.io/*  /${dir}/:splat  200!`);
  }
  lines.push('', '# Old single-site URLs move to the app hosts');
  for (const apex of APEXES) {
    for (const [host, dir] of Object.entries(APP_DIRS)) {
      lines.push(`${apex}/${dir}/*  https://${host}.crystalprism.io/:splat  301!`);
    }
  }
  return lines.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(ROOT, '_redirects'), buildRedirects());
}
